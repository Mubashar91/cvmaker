import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { buildDocument } from "../src/lib/pdf-document";
import { PDF_FONTS, SERIF_FONT_FILES } from "../src/lib/pdf-fonts";
import { collectionExampleCV, templateCollections } from "../src/lib/template-collections";

// Exports the ATS-friendly collection's example through the real PDF pipeline, extracts its text
// in reading order with pdf.js (as a parser would), and saves it for the collection page.
// Run after changing that example or the Clarity PDF layout: npx tsx scripts/build-ats-sample.ts
const require = createRequire(import.meta.url);
type TextItem = { str: string; transform: number[]; hasEOL?: boolean };

async function main() {
  const example = templateCollections.find(collection => collection.slug === "ats-friendly")?.example;
  if (!example) throw new Error("The ATS-friendly collection has no example.");
  const pdfMake = require("pdfmake/build/pdfmake");
  pdfMake.addVirtualFileSystem({
    ...require("pdfmake/build/vfs_fonts"),
    ...Object.fromEntries(await Promise.all(SERIF_FONT_FILES.map(async name => [name, (await readFile(`public/fonts/tinos/${name}`)).toString("base64")]))),
  });
  pdfMake.fonts = PDF_FONTS;
  const pdfjs = await import("pdfjs-dist/legacy/build/pdf.mjs");
  const buffer = await new Promise<Buffer>(resolve => pdfMake.createPdf(buildDocument(collectionExampleCV(example))).getBuffer(resolve));
  const pdf = await pdfjs.getDocument({ data: new Uint8Array(buffer) }).promise;
  const lines: string[] = [];
  try {
    for (let number = 1; number <= pdf.numPages; number++) {
      const content = await (await pdf.getPage(number)).getTextContent();
      let line = ""; let lastY: number | null = null;
      for (const item of content.items as TextItem[]) {
        const y = Math.round(item.transform[5]);
        if (lastY !== null && Math.abs(y - lastY) > 2) { if (line.trim()) lines.push(line.replace(/\s+/g, " ").trim()); line = ""; }
        line += line && !line.endsWith(" ") && item.str && !item.str.startsWith(" ") ? ` ${item.str}` : item.str;
        lastY = y;
      }
      if (line.trim()) lines.push(line.replace(/\s+/g, " ").trim());
    }
  } finally { await pdf.destroy(); }
  await writeFile("src/lib/generated/ats-sample-text.ts", `// Generated by scripts/build-ats-sample.ts from the real PDF export. Do not edit by hand.\nexport const atsSampleText = ${JSON.stringify(lines.join("\n"))};\n`);
  console.log(`Extracted ${lines.length} lines from the ATS example PDF.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
